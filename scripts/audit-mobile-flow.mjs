import { chromium, expect } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
const output = "test-results/mobile-flow";
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const records = [];
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce", colorScheme: "dark" });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("http://localhost:8081", { waitUntil: "load", timeout: 180000 });
  await page.getByRole("button", { name: "Sign in", exact: true }).waitFor({ timeout: 120000 });
  await page.screenshot({ path: `${output}/introduction-dark.png` });
  records.push({ check: "Signed-out launch shows introduction and authentication choices", passed: true });
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("button", { name: "Send sign-in code" }).waitFor();
  if (await page.getByLabel("Password", { exact: true }).count()) throw new Error("Sign-in still asks for an unsupported password");
  records.push({ check: "Introduction leads to email-code sign-in", passed: true });
  await page.getByRole("button", { name: "New here? Create an account" }).click();
  await page.getByLabel("Username", { exact: true }).waitFor();
  await page.getByLabel("Password", { exact: true }).waitFor();
  records.push({ check: "Account creation includes username and password", passed: true });
  await page.getByRole("button", { name: "Back to introduction" }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("radio", { name: "Light", exact: true }).click();
  await page.screenshot({ path: `${output}/settings-light.png` });
  await page.reload({ waitUntil: "load" });
  await page.getByRole("radio", { name: "Light · selected", exact: true }).waitFor();
  records.push({ check: "Explicit light preference survives reload on a dark device", passed: true });
  await page.getByRole("radio", { name: "Device setting", exact: true }).click();
  await page.emulateMedia({ colorScheme: "light" });
  const device = page.getByRole("radio", { name: "Device setting · selected", exact: true });
  await expect.poll(() => device.evaluate(el => getComputedStyle(el).backgroundColor)).toBe("rgb(255, 122, 22)");
  await page.emulateMedia({ colorScheme: "dark" });
  await expect.poll(() => device.evaluate(el => getComputedStyle(el).backgroundColor)).toBe("rgb(255, 138, 91)");
  await page.getByRole("radio", { name: "Dark", exact: true }).click();
  await page.screenshot({ path: `${output}/settings-dark.png` });
  records.push({ check: "Device mode updates live when the OS changes between light and dark", passed: true });
  await page.goto("http://localhost:8081/cart", { waitUntil: "load" });
  await page.getByRole("button", { name: "Sign in", exact: true }).waitFor();
  records.push({ check: "Signed-out deep link cannot open the account cart", passed: true });
  if (errors.length) throw new Error(errors.join("\n"));
  await context.close();
  const shopping = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce", colorScheme: "light" });
  const shop = await shopping.newPage();
  shop.setDefaultTimeout(120000);
  shop.on("pageerror", error => errors.push(error.message));
  await shop.goto("http://localhost:8081", { waitUntil: "load" });
  await shop.getByRole("button", { name: "Browse the shop", exact: true }).click();
  await shop.getByRole("textbox", { name: "Search products" }).waitFor();
  await shop.getByText("111 products", { exact: true }).waitFor();
  await shop.screenshot({ path: `${output}/shop-grid-light.png` });
  await shop.getByRole("textbox", { name: "Search products" }).fill("USB microphone");
  await shop.getByRole("button", { name: "View USB Podcast Microphone", exact: true }).waitFor();
  await shop.getByText("1 products", { exact: true }).waitFor();
  await shop.getByRole("button", { name: "View USB Podcast Microphone", exact: true }).click();
  await shop.getByText("Product details", { exact: true }).waitFor();
  await shop.getByRole("button", { name: "Add to cart", exact: true }).click();
  await shop.getByRole("button", { name: "Send sign-in code" }).waitFor();
  records.push({ check: "111 products, live search, product details and guest add-to-cart authentication", passed: true });
  await shop.getByRole("button", { name: "Back to the shop", exact: true }).click();
  await shop.getByRole("tab", { name: /Categories/ }).click();
  await shop.getByRole("button", { name: "Home Appliances", exact: true }).click();
  await shop.screenshot({ path: `${output}/categories-light.png` });
  await shop.getByText("Shop all 10 products", { exact: false }).waitFor();
  await shop.getByRole("tab", { name: /You/ }).click();
  await shop.getByRole("button", { name: "Sign in or create an account", exact: true }).waitFor();
  await shop.screenshot({ path: `${output}/account-light.png` });
  records.push({ check: "Bottom tabs, category sidebar and account page", passed: true });
  const overflow = await shop.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow) throw new Error("Mobile layout overflows the viewport");
  const clippedLabels = await shop.getByRole("tab").evaluateAll(tabs => tabs.filter(tab => [...tab.querySelectorAll('*')].some(child => child.childElementCount === 0 && child.textContent && child.getBoundingClientRect().bottom > innerHeight)).map(tab => tab.textContent));
  if (clippedLabels.length) throw new Error(`Bottom navigation labels are clipped: ${clippedLabels.join(', ')}`);
  if (errors.length) throw new Error(errors.join("\n"));
  await shopping.close();
  const website = await browser.newPage({ viewport: { width: 390, height: 844 }, colorScheme: "dark" });
  await website.goto("http://localhost:3000", { waitUntil: "load", timeout: 120000 });
  const mode = () => website.locator("html").getAttribute("data-scheme");
  await expect.poll(mode).toBe("dark");
  await website.getByRole("radio", { name: "Light", exact: true }).locator("..").click();
  await expect.poll(mode).toBe("light");
  await website.reload({ waitUntil: "load" });
  await expect.poll(mode).toBe("light");
  await website.getByRole("radio", { name: "Dark", exact: true }).locator("..").click();
  await expect.poll(mode).toBe("dark");
  await website.getByRole("radio", { name: "Auto", exact: true }).locator("..").click();
  await website.emulateMedia({ colorScheme: "light" });
  await expect.poll(mode).toBe("light");
  await website.emulateMedia({ colorScheme: "dark" });
  await expect.poll(mode).toBe("dark");
  records.push({ check: "Website follows device mode, supports manual light/dark and remembers the choice", passed: true });
  console.log(JSON.stringify(records, null, 2));
  await writeFile(`${output}/audit.json`, JSON.stringify(records, null, 2));
} finally { await browser.close(); }
